export function iconName(name) {
  return ICONS[name] ? name : (LEGACY[name?.replace(/️/g, '')] ?? name);
}

// Tamaño 1em por defecto: el ícono escala con el texto que lo rodea (text-xl, text-3xl…).
export default function Icon({ name, size = '1em', className = '', ...props }) {
  const Component = ICONS[iconName(name)];
  // Un emoji desconocido se muestra tal cual en vez de desaparecer.
  if (!Component) return name ? <span className={className}>{name}</span> : null;
  return <Component size={size} aria-hidden="true" className={`inline-block shrink-0 align-[-0.125em] ${className}`} {...props} />;
}
